"""Small, dependency-free state layer for the Pro update service.

This module deliberately contains no payment integration.  A license is a
high-entropy bearer token whose hash is the only token material retained in
SQLite.  Release paths are generated by the service and are never accepted
from an HTTP request.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import re
import secrets
import shutil
import sqlite3
import stat
import tempfile
import time
import zipfile
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timezone
from functools import cmp_to_key
from pathlib import Path
from typing import IO, Any, Dict, Iterable, Optional, Tuple


PRODUCT = "pro"
PACKAGE_NAME = "chat-archify-pro"
PACKAGE_MANIFEST_PATH = f"{PACKAGE_NAME}/package-manifest.json"
DEFAULT_LICENSE_DAYS = 365
MAX_NOTES_BYTES = 64 * 1024
TOKEN_BYTES = 48
TOKEN_MIN_LENGTH = 40
TOKEN_MAX_LENGTH = 512
RELEASE_ID_RE = re.compile(r"^rel_[A-Za-z0-9_-]{12,80}$")
SEMVER_RE = re.compile(
    r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)"
    r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
    r"(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?$"
)
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")


class ServiceError(Exception):
    """Safe, expected error that can be mapped to a generic HTTP response."""


class LicenseError(ServiceError):
    pass


class ReleaseError(ServiceError):
    pass


class ReleaseIntegrityError(ReleaseError):
    pass


@dataclass(frozen=True)
class LicenseRecord:
    license_id: str
    token_hash: str
    issued_at: int
    expires_at: Optional[int]
    revoked_at: Optional[int]
    product: str = PRODUCT


@dataclass(frozen=True)
class LicenseLookup:
    status: str
    record: Optional[LicenseRecord]


@dataclass(frozen=True)
class ReleaseRecord:
    release_id: str
    version: str
    notes: str
    sha256: str
    bytes: int
    relative_path: str
    published_at: int


def utc_now() -> int:
    return int(time.time())


def iso_utc(epoch: Optional[int]) -> Optional[str]:
    if epoch is None:
        return None
    return (
        datetime.fromtimestamp(int(epoch), tz=timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def hash_token(token: str) -> str:
    if not isinstance(token, str):
        raise LicenseError("invalid_license")
    if (
        len(token) < TOKEN_MIN_LENGTH
        or len(token) > TOKEN_MAX_LENGTH
        or any(char.isspace() or ord(char) < 32 for char in token)
    ):
        raise LicenseError("invalid_license")
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def validate_version(version: str) -> str:
    if not isinstance(version, str) or not SEMVER_RE.fullmatch(version):
        raise ReleaseError("invalid_version")
    return version


def validate_release_id(release_id: str) -> str:
    if not isinstance(release_id, str) or not RELEASE_ID_RE.fullmatch(release_id):
        raise ReleaseError("invalid_release")
    return release_id


def _semver_parts(version: str) -> Tuple[int, int, int, Optional[Tuple[str, ...]]]:
    match = SEMVER_RE.fullmatch(version)
    if not match:
        raise ReleaseError("invalid_version")
    pre = tuple(match.group(4).split(".")) if match.group(4) else None
    return int(match.group(1)), int(match.group(2)), int(match.group(3)), pre


def compare_versions(left: str, right: str) -> int:
    """Compare two validated SemVer strings, including pre-release ordering."""

    l_major, l_minor, l_patch, l_pre = _semver_parts(left)
    r_major, r_minor, r_patch, r_pre = _semver_parts(right)
    left_core = (l_major, l_minor, l_patch)
    right_core = (r_major, r_minor, r_patch)
    if left_core != right_core:
        return (left_core > right_core) - (left_core < right_core)
    if l_pre is None and r_pre is None:
        return 0
    if l_pre is None:
        return 1
    if r_pre is None:
        return -1
    for left_part, right_part in zip(l_pre, r_pre):
        if left_part == right_part:
            continue
        left_numeric = left_part.isdigit()
        right_numeric = right_part.isdigit()
        if left_numeric and right_numeric:
            return (int(left_part) > int(right_part)) - (
                int(left_part) < int(right_part)
            )
        if left_numeric != right_numeric:
            return -1 if left_numeric else 1
        return (left_part > right_part) - (left_part < right_part)
    return (len(l_pre) > len(r_pre)) - (len(l_pre) < len(r_pre))


def file_metadata(path: Path) -> Tuple[str, int]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
            size += len(chunk)
    return digest.hexdigest(), size


def _safe_archive_name(name: str, allow_directory: bool = False) -> str:
    if not isinstance(name, str) or not name or "\\" in name or name.startswith("/"):
        raise ReleaseError("unsafe_archive_path")
    if re.match(r"^[A-Za-z]:", name):
        raise ReleaseError("unsafe_archive_path")
    directory = name.endswith("/")
    clean = name[:-1] if directory else name
    parts = clean.split("/")
    if not clean or any(part in ("", ".", "..") for part in parts):
        raise ReleaseError("unsafe_archive_path")
    if directory and not allow_directory:
        raise ReleaseError("unsafe_archive_path")
    return clean + ("/" if directory else "")


def _manifest_entries(manifest: Any) -> Dict[str, Dict[str, Any]]:
    entries = manifest.get("files") if isinstance(manifest, dict) else None
    if isinstance(entries, dict):
        normalized = []
        for raw_path, raw_meta in entries.items():
            # The checked-in builder emits a relative-path -> SHA-256 map.
            # The richer list form below may additionally carry bytes.
            if isinstance(raw_meta, str):
                raw_meta = {"sha256": raw_meta}
            normalized.append({"path": raw_path, "meta": raw_meta, "map_shape": True})
    elif isinstance(entries, list):
        normalized = []
        for raw_entry in entries:
            if not isinstance(raw_entry, dict):
                raise ReleaseError("invalid_package_manifest")
            normalized.append({"path": raw_entry.get("path"), "meta": raw_entry, "map_shape": False})
    else:
        raise ReleaseError("invalid_package_manifest")

    result: Dict[str, Dict[str, Any]] = {}
    prefix = PACKAGE_NAME + "/"
    for item in normalized:
        raw_path = item.get("path")
        meta = item.get("meta")
        if not isinstance(raw_path, str) or not isinstance(meta, dict):
            raise ReleaseError("invalid_package_manifest")
        path = _safe_archive_name(raw_path)
        if not path.startswith(prefix):
            path = _safe_archive_name(prefix + path)
        if path == PACKAGE_MANIFEST_PATH or path in result:
            raise ReleaseError("invalid_package_manifest")
        digest = meta.get("sha256")
        size = meta.get("bytes", meta.get("size"))
        if not isinstance(digest, str) or not SHA256_RE.fullmatch(digest):
            raise ReleaseError("invalid_package_manifest")
        if item.get("map_shape"):
            # Map manifests intentionally contain hashes only; the service
            # reads each member's real byte count while hashing it.
            if size is not None:
                raise ReleaseError("invalid_package_manifest")
        elif (
            isinstance(size, bool)
            or not isinstance(size, int)
            or size < 0
        ):
            raise ReleaseError("invalid_package_manifest")
        result[path] = {"sha256": digest, "bytes": size}
    return result


def _zip_member_metadata(archive: zipfile.ZipFile, info: zipfile.ZipInfo) -> Tuple[str, int]:
    digest = hashlib.sha256()
    size = 0
    with archive.open(info, "r") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
            size += len(chunk)
    return digest.hexdigest(), size


def validate_package_zip(source_zip: os.PathLike[str] | str, expected_version: str) -> Dict[str, Any]:
    """Validate package identity and per-file metadata without extracting it."""

    expected_version = validate_version(expected_version)
    try:
        with zipfile.ZipFile(Path(source_zip), "r") as archive:
            infos = archive.infolist()
            by_name: Dict[str, zipfile.ZipInfo] = {}
            file_names = []
            for info in infos:
                name = _safe_archive_name(info.filename, allow_directory=True)
                if name in by_name:
                    raise ReleaseError("invalid_package_manifest")
                mode = (info.external_attr >> 16) & 0o170000
                if mode and stat.S_ISLNK(mode):
                    raise ReleaseError("unsafe_archive_path")
                if info.flag_bits & 0x1:
                    raise ReleaseError("encrypted_archive")
                if not name.startswith(PACKAGE_NAME + "/"):
                    raise ReleaseError("unsafe_archive_path")
                by_name[name] = info
                if not info.is_dir():
                    file_names.append(name)
            if file_names.count(PACKAGE_MANIFEST_PATH) != 1:
                raise ReleaseError("invalid_package_manifest")
            manifest_info = by_name[PACKAGE_MANIFEST_PATH]
            try:
                manifest = json.loads(archive.read(manifest_info).decode("utf-8"))
            except (UnicodeDecodeError, ValueError, KeyError):
                raise ReleaseError("invalid_package_manifest")
            if (
                not isinstance(manifest, dict)
                or manifest.get("name") != PACKAGE_NAME
                or manifest.get("version") != expected_version
            ):
                raise ReleaseError("package_identity_mismatch")
            entries = _manifest_entries(manifest)
            actual_files = set(file_names) - {PACKAGE_MANIFEST_PATH}
            if set(entries) != actual_files:
                raise ReleaseError("package_file_list_mismatch")
            for path, expected in entries.items():
                digest, size = _zip_member_metadata(archive, by_name[path])
                if digest != expected["sha256"] or (
                    expected["bytes"] is not None and size != expected["bytes"]
                ):
                    raise ReleaseError("package_file_integrity_mismatch")
            return manifest
    except ReleaseError:
        raise
    except (OSError, KeyError, RuntimeError, ValueError, zipfile.BadZipFile, zipfile.LargeZipFile):
        raise ReleaseError("invalid_package_manifest")


def _row_to_license(row: sqlite3.Row) -> LicenseRecord:
    return LicenseRecord(
        license_id=str(row["license_id"]),
        token_hash=str(row["token_hash"]),
        issued_at=int(row["issued_at"]),
        expires_at=int(row["expires_at"]) if row["expires_at"] is not None else None,
        revoked_at=int(row["revoked_at"]) if row["revoked_at"] is not None else None,
        product=str(row["product"]),
    )


def _row_to_release(row: sqlite3.Row) -> ReleaseRecord:
    return ReleaseRecord(
        release_id=str(row["release_id"]),
        version=str(row["version"]),
        notes=str(row["notes"]),
        sha256=str(row["sha256"]),
        bytes=int(row["bytes"]),
        relative_path=str(row["relative_path"]),
        published_at=int(row["published_at"]),
    )


class Store:
    """SQLite-backed licenses and release registry.

    A new connection is used for every operation so the HTTP server can use
    the store from its worker threads without sharing a SQLite connection.
    """

    def __init__(self, db_path: os.PathLike[str] | str, release_dir: os.PathLike[str] | str):
        self.db_path = Path(db_path).expanduser().resolve()
        self.release_dir = Path(release_dir).expanduser().resolve()
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self.release_dir.mkdir(parents=True, exist_ok=True)
        self._initialize()

    def _connect(self) -> sqlite3.Connection:
        connection = sqlite3.connect(str(self.db_path), timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute("PRAGMA busy_timeout = 5000")
        connection.execute("PRAGMA journal_mode = WAL")
        return connection

    @contextmanager
    def _connection(self):
        connection = self._connect()
        try:
            yield connection
        except Exception:
            connection.rollback()
            raise
        else:
            connection.commit()
        finally:
            connection.close()

    def _initialize(self) -> None:
        with self._connection() as connection:
            connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS licenses (
                    license_id TEXT PRIMARY KEY,
                    token_hash TEXT NOT NULL UNIQUE,
                    issued_at INTEGER NOT NULL,
                    expires_at INTEGER,
                    revoked_at INTEGER,
                    product TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS releases (
                    release_id TEXT PRIMARY KEY,
                    version TEXT NOT NULL UNIQUE,
                    notes TEXT NOT NULL,
                    sha256 TEXT NOT NULL,
                    bytes INTEGER NOT NULL,
                    relative_path TEXT NOT NULL UNIQUE,
                    published_at INTEGER NOT NULL
                );
                CREATE INDEX IF NOT EXISTS idx_releases_published
                    ON releases (published_at);
                """
            )

    def issue_license(
        self,
        output_path: os.PathLike[str] | str,
        days: Optional[int] = DEFAULT_LICENSE_DAYS,
        perpetual: bool = False,
        now: Optional[int] = None,
        product: str = PRODUCT,
    ) -> Tuple[LicenseRecord, str]:
        if perpetual and days not in (None, DEFAULT_LICENSE_DAYS):
            raise LicenseError("days_and_perpetual_are_mutually_exclusive")
        if not perpetual:
            if days is None or isinstance(days, bool) or int(days) <= 0:
                raise LicenseError("invalid_license_days")
            days = int(days)
        issued_at = utc_now() if now is None else int(now)
        expires_at = None if perpetual else issued_at + int(days) * 86400
        token = secrets.token_urlsafe(TOKEN_BYTES)
        token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()
        license_id = "lic_" + secrets.token_urlsafe(12)
        record = LicenseRecord(
            license_id=license_id,
            token_hash=token_hash,
            issued_at=issued_at,
            expires_at=expires_at,
            revoked_at=None,
            product=product,
        )
        output = Path(output_path).expanduser()
        if output.exists():
            raise LicenseError("license_file_exists")
        if not output.parent.exists():
            raise LicenseError("license_parent_missing")
        temp_name: Optional[str] = None
        inserted = False
        try:
            with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                newline="\n",
                prefix=f".{output.name}.",
                suffix=".tmp",
                dir=str(output.parent),
                delete=False,
            ) as temporary:
                temp_name = temporary.name
                os.chmod(temp_name, 0o600)
                json.dump(
                    {
                        "token": token,
                        "license_id": license_id,
                        "product": product,
                        "issued_at": iso_utc(issued_at),
                        "expires_at": iso_utc(expires_at),
                    },
                    temporary,
                    ensure_ascii=False,
                    separators=(",", ":"),
                )
                temporary.write("\n")
                temporary.flush()
                os.fsync(temporary.fileno())
            with self._connection() as connection:
                connection.execute(
                    """
                    INSERT INTO licenses
                        (license_id, token_hash, issued_at, expires_at, revoked_at, product)
                    VALUES (?, ?, ?, ?, NULL, ?)
                    """,
                    (license_id, token_hash, issued_at, expires_at, product),
                )
                inserted = True
            os.replace(temp_name, output)
            temp_name = None
        except Exception:
            if inserted:
                with self._connection() as connection:
                    connection.execute("DELETE FROM licenses WHERE license_id = ?", (license_id,))
            if temp_name:
                try:
                    os.unlink(temp_name)
                except OSError:
                    pass
            raise
        return record, token

    def revoke_license(
        self, license_id: Optional[str] = None, token: Optional[str] = None, now: Optional[int] = None
    ) -> bool:
        if not license_id and not token:
            raise LicenseError("license_id_or_file_required")
        if token is not None:
            token_hash = hash_token(token)
            query = "SELECT license_id FROM licenses WHERE token_hash = ?"
            args: Tuple[Any, ...] = (token_hash,)
        else:
            query = "SELECT license_id FROM licenses WHERE license_id = ?"
            args = (license_id,)
        with self._connection() as connection:
            row = connection.execute(query, args).fetchone()
            if row is None:
                return False
            revoked_at = utc_now() if now is None else int(now)
            connection.execute(
                "UPDATE licenses SET revoked_at = COALESCE(revoked_at, ?) WHERE license_id = ?",
                (revoked_at, str(row["license_id"])),
            )
            return True

    def lookup_token(self, token: Optional[str], now: Optional[int] = None) -> LicenseLookup:
        if token is None:
            return LicenseLookup("missing", None)
        try:
            token_hash = hash_token(token)
        except LicenseError:
            return LicenseLookup("invalid", None)
        with self._connection() as connection:
            row = connection.execute(
                "SELECT * FROM licenses WHERE token_hash = ?", (token_hash,)
            ).fetchone()
        if row is None:
            return LicenseLookup("invalid", None)
        record = _row_to_license(row)
        current = utc_now() if now is None else int(now)
        if record.revoked_at is not None:
            return LicenseLookup("revoked", record)
        if record.expires_at is not None and current >= record.expires_at:
            return LicenseLookup("expired", record)
        return LicenseLookup("active", record)

    def register_release(
        self,
        version: str,
        source_zip: os.PathLike[str] | str,
        notes: str = "",
        published_at: Optional[int] = None,
    ) -> ReleaseRecord:
        version = validate_version(version)
        if not isinstance(notes, str) or len(notes.encode("utf-8")) > MAX_NOTES_BYTES:
            raise ReleaseError("notes_too_large")
        source = Path(source_zip).expanduser().resolve()
        if not source.is_file() or not zipfile.is_zipfile(source):
            raise ReleaseError("invalid_zip")
        validate_package_zip(source, version)
        release_id = "rel_" + secrets.token_urlsafe(12)
        relative_path = f"{release_id}.zip"
        destination = self._safe_release_path(relative_path, allow_missing=True)
        temporary_path: Optional[str] = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="wb",
                prefix=f".{release_id}.",
                suffix=".tmp",
                dir=str(self.release_dir),
                delete=False,
            ) as temporary:
                temporary_path = temporary.name
                with source.open("rb") as source_stream:
                    shutil.copyfileobj(source_stream, temporary, length=1024 * 1024)
                temporary.flush()
                os.fsync(temporary.fileno())
            os.replace(temporary_path, destination)
            temporary_path = None
            # Re-validate the exact copied bytes before publishing their
            # manifest row; the administrator's source may have changed
            # between the initial preflight and the copy.
            validate_package_zip(destination, version)
            digest, size = file_metadata(destination)
            record = ReleaseRecord(
                release_id=release_id,
                version=version,
                notes=notes,
                sha256=digest,
                bytes=size,
                relative_path=relative_path,
                published_at=utc_now() if published_at is None else int(published_at),
            )
            with self._connection() as connection:
                connection.execute(
                    """
                    INSERT INTO releases
                        (release_id, version, notes, sha256, bytes, relative_path, published_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        record.release_id,
                        record.version,
                        record.notes,
                        record.sha256,
                        record.bytes,
                        record.relative_path,
                        record.published_at,
                    ),
                )
        except ReleaseError:
            if temporary_path:
                try:
                    os.unlink(temporary_path)
                except OSError:
                    pass
            if destination.exists():
                try:
                    destination.unlink()
                except OSError:
                    pass
            raise
        except Exception:
            if temporary_path:
                try:
                    os.unlink(temporary_path)
                except OSError:
                    pass
            if destination.exists():
                try:
                    destination.unlink()
                except OSError:
                    pass
            raise ReleaseError("release_register_failed")
        return record

    def release_by_id(self, release_id: str) -> Optional[ReleaseRecord]:
        try:
            validate_release_id(release_id)
        except ReleaseError:
            return None
        with self._connection() as connection:
            row = connection.execute(
                "SELECT * FROM releases WHERE release_id = ?", (release_id,)
            ).fetchone()
        return _row_to_release(row) if row is not None else None

    def latest_release(self) -> Optional[ReleaseRecord]:
        with self._connection() as connection:
            rows = connection.execute("SELECT * FROM releases").fetchall()
        records = [_row_to_release(row) for row in rows]
        if not records:
            return None
        return max(records, key=cmp_to_key(lambda left, right: compare_versions(left.version, right.version)))

    def _safe_release_path(self, relative_path: str, allow_missing: bool = False) -> Path:
        if (
            not relative_path
            or "\\" in relative_path
            or Path(relative_path).is_absolute()
            or any(part in ("", ".", "..") for part in Path(relative_path).parts)
        ):
            raise ReleaseIntegrityError("release_integrity_failure")
        base = self.release_dir.resolve()
        try:
            candidate = (base / relative_path).resolve(strict=not allow_missing)
        except OSError as error:
            raise ReleaseIntegrityError('release_integrity_failure') from error
        try:
            common = os.path.commonpath((str(base), str(candidate)))
        except ValueError:
            raise ReleaseIntegrityError("release_integrity_failure")
        if common != str(base) or candidate == base:
            raise ReleaseIntegrityError("release_integrity_failure")
        if not allow_missing and not candidate.is_file():
            raise ReleaseIntegrityError("release_integrity_failure")
        return candidate

    def snapshot_release(self, release: ReleaseRecord) -> Tuple[IO[bytes], str, int]:
        """Hash and snapshot one open source stream before it is sent.

        The HTTP layer streams the returned temporary file, so the bytes sent
        are exactly the bytes that were hashed.  The source stat is checked
        before and after the copy to catch a replacement during verification.
        """

        source_path = self._safe_release_path(release.relative_path)
        snapshot = tempfile.SpooledTemporaryFile(max_size=8 * 1024 * 1024, mode="w+b")
        digest = hashlib.sha256()
        size = 0
        try:
            with source_path.open("rb") as source:
                before = os.fstat(source.fileno())
                for chunk in iter(lambda: source.read(1024 * 1024), b""):
                    snapshot.write(chunk)
                    digest.update(chunk)
                    size += len(chunk)
                after = os.fstat(source.fileno())
            identity_before = (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns)
            identity_after = (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            actual_hash = digest.hexdigest()
            if identity_before != identity_after or actual_hash != release.sha256 or size != release.bytes:
                raise ReleaseIntegrityError("release_integrity_failure")
            snapshot.seek(0)
            return snapshot, actual_hash, size
        except OSError as error:
            snapshot.close()
            raise ReleaseIntegrityError('release_integrity_failure') from error
        except Exception:
            snapshot.close()
            raise

    def release_payload(self, release: Optional[ReleaseRecord]) -> Optional[Dict[str, Any]]:
        if release is None:
            return None
        return {
            "id": release.release_id,
            "version": release.version,
            "notes": release.notes,
            "sha256": release.sha256,
            "bytes": release.bytes,
            "published_at": iso_utc(release.published_at),
            "download_path": f"/api/v1/updates/releases/{release.release_id}/download",
        }


def load_license_token(path: os.PathLike[str] | str) -> str:
    try:
        with Path(path).expanduser().open("r", encoding="utf-8") as source:
            document = json.load(source)
        token = document.get("license") or document.get("token")
    except (OSError, ValueError, AttributeError, TypeError):
        raise LicenseError("invalid_license_file")
    if not isinstance(token, str):
        raise LicenseError("invalid_license_file")
    # Reuse the strict validation without returning the hash or token in errors.
    hash_token(token)
    return token


def parse_bearer_header(value: Optional[str]) -> Optional[str]:
    if value is None:
        return None
    if not isinstance(value, str):
        raise LicenseError("invalid_license")
    parts = value.strip().split()
    if len(parts) != 2 or parts[0].casefold() != "bearer":
        raise LicenseError("invalid_license")
    token = parts[1]
    hash_token(token)
    return token


def constant_time_equal(left: str, right: str) -> bool:
    return hmac.compare_digest(left.encode("ascii"), right.encode("ascii"))
